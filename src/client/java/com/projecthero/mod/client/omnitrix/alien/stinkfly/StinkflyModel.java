package com.projecthero.mod.client.omnitrix.alien.stinkfly;

import com.projecthero.mod.ProjectHeroMod;

import net.minecraft.resources.ResourceLocation;
import net.minecraft.util.Mth;
import net.minecraft.world.entity.player.Player;

import software.bernie.geckolib.animatable.GeoAnimatable;
import software.bernie.geckolib.animation.AnimationState;
import software.bernie.geckolib.constant.DataTickets;
import software.bernie.geckolib.model.GeoModel;
import software.bernie.geckolib.model.data.EntityModelData;

/**
 * v0.17.1: Stinkfly's GeckoLib model -- {@code geo/omnitrix/stinkfly.geo.json}, {@code textures/entity/omnitrix/stinkfly.png}
 * (+ {@code stinkfly_glowmask.png}: the eyes and a faint wing glow), {@code animations/omnitrix/stinkfly.animation.json}, all
 * generated by {@code scratchpad/stinkfly_v0171/gen_stinkfly.js}. The head turns to where the player looks on its own
 * {@code look} bone (no clip keys it); not while he dives head-first.
 */
public class StinkflyModel<T extends GeoAnimatable> extends GeoModel<T> {
	public static final ResourceLocation GEO = ProjectHeroMod.id("geo/omnitrix/stinkfly.geo.json");
	public static final ResourceLocation TEXTURE = ProjectHeroMod.id("textures/entity/omnitrix/stinkfly.png");
	public static final ResourceLocation ANIMATION = ProjectHeroMod.id("animations/omnitrix/stinkfly.animation.json");

	@Override
	public ResourceLocation getModelResource(T animatable) {
		return GEO;
	}

	@Override
	public ResourceLocation getTextureResource(T animatable) {
		return TEXTURE;
	}

	@Override
	public ResourceLocation getAnimationResource(T animatable) {
		return ANIMATION;
	}

	@Override
	public void setCustomAnimations(T animatable, long instanceId, AnimationState<T> state) {
		EntityModelData data = state.getData(DataTickets.ENTITY_MODEL_DATA);
		Object e = state.getData(DataTickets.ENTITY);
		getBone("look").ifPresent(look -> {
			if (data == null || !(e instanceof Player p) || StinkflyAnimatable.diving(p)) {
				look.setRotX(0);
				look.setRotY(0);
				return;
			}
			look.setRotX(Mth.clamp(data.headPitch(), -50f, 50f) * 0.8f * Mth.DEG_TO_RAD);
			// wrapped: GeckoLib's head-minus-body yaw is not (head 170 against body -179 read as 349, so the head sat turned to the clamp)
			look.setRotY(Mth.clamp(Mth.wrapDegrees(data.netHeadYaw()), -70f, 70f) * 0.85f * Mth.DEG_TO_RAD);
		});
	}
}
