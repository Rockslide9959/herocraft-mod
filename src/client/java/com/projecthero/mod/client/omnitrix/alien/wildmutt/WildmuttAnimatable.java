package com.projecthero.mod.client.omnitrix.alien.wildmutt;

import java.util.Map;
import java.util.WeakHashMap;

import com.projecthero.mod.omnitrix.Omnitrix;
import com.projecthero.mod.omnitrix.alien.Aliens;
import com.projecthero.mod.omnitrix.alien.wildmutt.WildmuttKit;
import com.projecthero.mod.omnitrix.data.OmnitrixState;

import net.minecraft.core.BlockPos;
import net.minecraft.util.Mth;
import net.minecraft.world.entity.EntityType;
import net.minecraft.world.entity.HumanoidArm;
import net.minecraft.world.entity.player.Player;
import net.minecraft.world.phys.Vec3;

import software.bernie.geckolib.animatable.GeoReplacedEntity;
import software.bernie.geckolib.animatable.instance.AnimatableInstanceCache;
import software.bernie.geckolib.animation.AnimatableManager;
import software.bernie.geckolib.animation.AnimationController;
import software.bernie.geckolib.animation.AnimationState;
import software.bernie.geckolib.animation.PlayState;
import software.bernie.geckolib.animation.RawAnimation;
import software.bernie.geckolib.constant.DataTickets;
import software.bernie.geckolib.util.GeckoLibUtil;

/**
 * v0.17.1: the GeckoLib animatable drawn in place of a player who is Wildmutt (one singleton; GeckoLib keys each player's
 * animation state by entity id). Clips from {@code animations/omnitrix/wildmutt.animation.json} (generated by
 * {@code scratchpad/wildmutt_v0171/anims.js}). Three controllers:
 * <ul>
 *   <li>{@code main}: the kit's synced move clip while it plays (pounce, maul, quills, roar, slam, frenzy, track, sniff), the
 *       held ones from the kit's flags (the coil, the Quill Roll, the wall climb), else air / gallop / walk / sneak / idle (with
 *       an occasional sniff while he stands still);</li>
 *   <li>{@code swing}: the Attack claw swipe on one front arm, alternating right / left;</li>
 *   <li>{@code hurt}: the flinch, on its own bone.</li>
 * </ul>
 * Clip speeds never change (GeckoLib rescales a clip's whole elapsed time with its speed, so it would jump).
 */
public final class WildmuttAnimatable implements GeoReplacedEntity {
	public static final WildmuttAnimatable INSTANCE = new WildmuttAnimatable();

	private static final String P = "animation.projecthero.wildmutt.";
	private static final RawAnimation IDLE = RawAnimation.begin().thenLoop(P + "idle");
	private static final RawAnimation IDLE_SNIFF = RawAnimation.begin().thenPlay(P + "idle_sniff");
	private static final RawAnimation WALK = RawAnimation.begin().thenLoop(P + "walk");
	private static final RawAnimation SNEAK = RawAnimation.begin().thenLoop(P + "sneak");
	private static final RawAnimation GALLOP = RawAnimation.begin().thenLoop(P + "gallop");
	private static final RawAnimation AIR = RawAnimation.begin().thenPlayAndHold(P + "air");
	private static final RawAnimation COIL = RawAnimation.begin().thenLoop(P + "leap_charge");
	private static final RawAnimation CLIMB = RawAnimation.begin().thenLoop(P + "climb");
	private static final RawAnimation ROLL = RawAnimation.begin().thenLoop(P + "roll");
	private static final RawAnimation POUNCE = RawAnimation.begin().thenPlay(P + "pounce");
	private static final RawAnimation MAUL = RawAnimation.begin().thenPlay(P + "maul");
	private static final RawAnimation QUILLS = RawAnimation.begin().thenPlay(P + "quills");
	private static final RawAnimation ROAR = RawAnimation.begin().thenPlay(P + "roar");
	private static final RawAnimation SLAM = RawAnimation.begin().thenPlay(P + "slam");
	private static final RawAnimation FRENZY = RawAnimation.begin().thenPlay(P + "frenzy");
	private static final RawAnimation TRACK = RawAnimation.begin().thenPlay(P + "track");
	private static final RawAnimation SWIPE_R = RawAnimation.begin().thenPlay(P + "swipe_r");
	private static final RawAnimation SWIPE_L = RawAnimation.begin().thenPlay(P + "swipe_l");
	private static final RawAnimation HURT = RawAnimation.begin().thenPlay(P + "hurt");

	/** Ticks each move clip owns the body after its synced start (the clip's length + 1). */
	public static int oneShotTicks(int animId) {
		return switch (animId) {
			case WildmuttKit.ANIM_POUNCE -> 18;
			case WildmuttKit.ANIM_MAUL -> 22;
			case WildmuttKit.ANIM_QUILLS -> 15;
			case WildmuttKit.ANIM_ROAR -> 29;
			case WildmuttKit.ANIM_SLAM -> 21;
			case WildmuttKit.ANIM_FRENZY -> 25;
			case WildmuttKit.ANIM_TRACK -> 25;
			case WildmuttKit.ANIM_SNIFF -> 25;
			default -> 0;
		};
	}

	private static RawAnimation oneShot(int animId) {
		return switch (animId) {
			case WildmuttKit.ANIM_POUNCE -> POUNCE;
			case WildmuttKit.ANIM_MAUL -> MAUL;
			case WildmuttKit.ANIM_QUILLS -> QUILLS;
			case WildmuttKit.ANIM_ROAR -> ROAR;
			case WildmuttKit.ANIM_SLAM -> SLAM;
			case WildmuttKit.ANIM_FRENZY -> FRENZY;
			case WildmuttKit.ANIM_TRACK, WildmuttKit.ANIM_SNIFF -> TRACK;
			default -> null;
		};
	}

	/** A move clip that uses both front arms (the swipe layer stays off it). */
	private static boolean ownsArms(int animId) {
		return animId == WildmuttKit.ANIM_POUNCE || animId == WildmuttKit.ANIM_MAUL || animId == WildmuttKit.ANIM_SLAM
				|| animId == WildmuttKit.ANIM_FRENZY;
	}

	/** Client render thread only: per player, the move start last played / when he last stood still / the swipe side. */
	private static final Map<Player, Long> LAST_START = new WeakHashMap<>();
	private static final Map<Player, Long> STILL_SINCE = new WeakHashMap<>();
	private static final Map<Player, boolean[]> SWIPE = new WeakHashMap<>();

	private final AnimatableInstanceCache cache = GeckoLibUtil.createInstanceCache(this);

	private WildmuttAnimatable() {
	}

	@Override
	public EntityType<?> getReplacingEntityType() {
		return EntityType.PLAYER;
	}

	@Override
	public void registerControllers(AnimatableManager.ControllerRegistrar controllers) {
		controllers.add(new AnimationController<>(this, "main", 4, this::main));
		controllers.add(new AnimationController<>(this, "swing", 2, this::swing));
		controllers.add(new AnimationController<>(this, "hurt", 1, this::hurt));
	}

	static WildmuttKit kit() {
		return (WildmuttKit) Aliens.kit(WildmuttKit.ID);
	}

	/** Climbing (both sides of the wire): Wall Climb on, pressed to a wall and off the ground or going up it. */
	public static boolean climbing(Player p) {
		WildmuttKit k = kit();
		if (k == null || !k.flag(p, WildmuttKit.F_CLIMB) || k.flag(p, WildmuttKit.F_ROLL)) {
			return false;
		}
		if (p.horizontalCollision && p.onClimbable()) {
			return true;
		}
		// another player: horizontalCollision is never computed for them here -- a wall right in front at body height will do
		float yaw = p.yBodyRot * Mth.DEG_TO_RAD;
		Vec3 f = new Vec3(-Mth.sin(yaw), 0, Mth.cos(yaw));
		double reach = p.getBbWidth() * 0.5 + 0.3;
		BlockPos at = BlockPos.containing(p.getX() + f.x * reach, p.getY() + 0.6, p.getZ() + f.z * reach);
		boolean wall = !p.level().getBlockState(at).getCollisionShape(p.level(), at).isEmpty();
		return wall && (!p.onGround() || p.getY() - p.yo > 0.01);
	}

	private PlayState main(AnimationState<WildmuttAnimatable> state) {
		if (!(state.getData(DataTickets.ENTITY) instanceof Player p) || !Omnitrix.hasPower(p)) {
			return state.setAndContinue(IDLE);
		}
		OmnitrixState s = Omnitrix.state(p);
		WildmuttKit k = kit();
		long now = p.level().getGameTime();
		long since = now - s.animStart;
		if (k != null && k.flag(p, WildmuttKit.F_ROLL)) {
			return state.setAndContinue(ROLL);
		}
		if (k != null && k.flag(p, WildmuttKit.F_COIL)) {
			return state.setAndContinue(COIL);
		}
		int len = oneShotTicks(s.animId);
		if (len > 0 && since >= 0 && since < len) {
			Long last = LAST_START.get(p);
			if (last != null && last != s.animStart) {
				state.getController().forceAnimationReset(); // the same move again: from the top
			}
			LAST_START.put(p, s.animStart);
			STILL_SINCE.remove(p);
			return state.setAndContinue(oneShot(s.animId));
		}
		if (climbing(p)) {
			return state.setAndContinue(CLIMB);
		}
		double dx = p.getX() - p.xo, dz = p.getZ() - p.zo;
		double speed = Math.sqrt(dx * dx + dz * dz);
		if (!p.onGround() && !p.isInWater() && !p.onClimbable() && (p.getY() - p.yo > 0.08 || p.fallDistance > 0.6f
				|| (k != null && k.flag(p, WildmuttKit.F_LEAPING)))) {
			STILL_SINCE.remove(p);
			return state.setAndContinue(AIR);
		}
		if (speed > 0.015) {
			STILL_SINCE.remove(p);
			if (p.isCrouching()) {
				return state.setAndContinue(SNEAK);
			}
			return state.setAndContinue(p.isSprinting() || speed > 0.36 ? GALLOP : WALK);
		}
		// standing: now and then he drops his nose for a sniff
		long still = STILL_SINCE.computeIfAbsent(p, q -> now);
		long t = now - still;
		if (t > 140 && (t - 140) % 320 < 52) {
			return state.setAndContinue(IDLE_SNIFF);
		}
		return state.setAndContinue(IDLE);
	}

	private PlayState swing(AnimationState<WildmuttAnimatable> state) {
		if (!(state.getData(DataTickets.ENTITY) instanceof Player p) || !Omnitrix.hasPower(p)) {
			return PlayState.STOP;
		}
		OmnitrixState s = Omnitrix.state(p);
		WildmuttKit k = kit();
		boolean busy = (ownsArms(s.animId) && p.level().getGameTime() - s.animStart < oneShotTicks(s.animId))
				|| (k != null && (k.flag(p, WildmuttKit.F_ROLL) || k.flag(p, WildmuttKit.F_COIL))) || climbing(p);
		boolean[] side = SWIPE.computeIfAbsent(p, q -> new boolean[] { false, false }); // { swinging last frame, left next }
		if (p.swinging && !side[0]) {
			side[1] = !side[1];
			state.getController().forceAnimationReset();
		}
		side[0] = p.swinging;
		if (busy || !p.swinging) {
			if (!p.swinging) {
				state.getController().forceAnimationReset();
			}
			return PlayState.STOP;
		}
		boolean left = p.getMainArm() == HumanoidArm.LEFT ? !side[1] : side[1];
		return state.setAndContinue(left ? SWIPE_L : SWIPE_R);
	}

	private PlayState hurt(AnimationState<WildmuttAnimatable> state) {
		if (state.getData(DataTickets.ENTITY) instanceof Player p && p.hurtTime > 0) {
			if (p.hurtTime == p.hurtDuration) {
				state.getController().forceAnimationReset();
			}
			return state.setAndContinue(HURT);
		}
		state.getController().forceAnimationReset();
		return PlayState.STOP;
	}

	@Override
	public AnimatableInstanceCache getAnimatableInstanceCache() {
		return cache;
	}
}
