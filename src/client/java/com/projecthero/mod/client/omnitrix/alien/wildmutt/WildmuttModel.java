package com.projecthero.mod.client.omnitrix.alien.wildmutt;

import com.projecthero.mod.ProjectHeroMod;
import com.projecthero.mod.omnitrix.alien.wildmutt.WildmuttKit;

import net.minecraft.resources.ResourceLocation;
import net.minecraft.util.Mth;
import net.minecraft.world.entity.player.Player;

import software.bernie.geckolib.animatable.GeoAnimatable;
import software.bernie.geckolib.animation.AnimationState;
import software.bernie.geckolib.constant.DataTickets;
import software.bernie.geckolib.model.GeoModel;
import software.bernie.geckolib.model.data.EntityModelData;

/**
 * v0.17.1: Wildmutt's GeckoLib model -- {@code geo/omnitrix/wildmutt.geo.json}, {@code textures/entity/omnitrix/wildmutt.png},
 * {@code animations/omnitrix/wildmutt.animation.json}, all generated by {@code scratchpad/wildmutt_v0171/gen_wildmutt.js}. The
 * head turns to where the player looks on its own {@code look} bone (no clip keys it), damped: he is blind, so the whole head
 * points his gills at the sound rather than following the eyes exactly.
 */
public class WildmuttModel<T extends GeoAnimatable> extends GeoModel<T> {
	public static final ResourceLocation GEO = ProjectHeroMod.id("geo/omnitrix/wildmutt.geo.json");
	public static final ResourceLocation TEXTURE = ProjectHeroMod.id("textures/entity/omnitrix/wildmutt.png");
	public static final ResourceLocation ANIMATION = ProjectHeroMod.id("animations/omnitrix/wildmutt.animation.json");

	@Override
	public ResourceLocation getModelResource(T animatable) {
		return GEO;
	}

	@Override
	public ResourceLocation getTextureResource(T animatable) {
		return TEXTURE;
	}

	@Override
	public ResourceLocation getAnimationResource(T animatable) {
		return ANIMATION;
	}

	@Override
	public void setCustomAnimations(T animatable, long instanceId, AnimationState<T> state) {
		EntityModelData data = state.getData(DataTickets.ENTITY_MODEL_DATA);
		Object e = state.getData(DataTickets.ENTITY);
		getBone("look").ifPresent(look -> {
			boolean free = data != null && e instanceof Player p && !WildmuttAnimatable.climbing(p)
					&& !(WildmuttAnimatable.kit() != null && WildmuttAnimatable.kit().flag(p, WildmuttKit.F_ROLL));
			if (!free) {
				look.setRotX(0);
				look.setRotY(0);
				return;
			}
			look.setRotX(Mth.clamp(data.headPitch(), -40f, 40f) * 0.55f * Mth.DEG_TO_RAD);
			look.setRotY(Mth.clamp(data.netHeadYaw(), -60f, 60f) * 0.6f * Mth.DEG_TO_RAD);
		});
	}
}
