package com.projecthero.mod.client.omnitrix.alien.stinkfly;

import java.util.Map;
import java.util.WeakHashMap;

import com.projecthero.mod.omnitrix.Omnitrix;
import com.projecthero.mod.omnitrix.alien.stinkfly.StinkflyKit;
import com.projecthero.mod.omnitrix.data.OmnitrixState;

import net.minecraft.world.entity.EntityType;
import net.minecraft.world.entity.HumanoidArm;
import net.minecraft.world.entity.player.Player;

import software.bernie.geckolib.animatable.GeoReplacedEntity;
import software.bernie.geckolib.animatable.instance.AnimatableInstanceCache;
import software.bernie.geckolib.animation.AnimatableManager;
import software.bernie.geckolib.animation.AnimationController;
import software.bernie.geckolib.animation.AnimationState;
import software.bernie.geckolib.animation.PlayState;
import software.bernie.geckolib.animation.RawAnimation;
import software.bernie.geckolib.constant.DataTickets;
import software.bernie.geckolib.util.GeckoLibUtil;

/**
 * v0.17.1: the GeckoLib animatable drawn in place of a player who is Stinkfly (one singleton; GeckoLib keys each player's
 * animation state by entity id). Clips from {@code animations/omnitrix/stinkfly.animation.json} (generated by
 * {@code scratchpad/stinkfly_v0171/anims.js}). Five controllers, the later ones winning on the bones they key:
 * <ul>
 *   <li>{@code main}: the body -- the held dive, the whole-body moves (dash, take-off, splash-down, lift), carrying a creature,
 *       else fly / hover in the air (the kit's synced flying flag) and walk / idle on the ground;</li>
 *   <li>{@code move}: the upper-body moves (spit, barrage, net, gas, stab, the attack's stinger flick, gust, storm) on the head,
 *       jaw, chest, arms and tail, so they play over the hover or the walk;</li>
 *   <li>{@code wings}: folded on the ground (a flutter now and then), the hover buzz, the flight beat, the dive sweep, the gust's
 *       great flap;</li>
 *   <li>{@code swing}: the Attack claw jab on one arm, alternating right / left;</li>
 *   <li>{@code hurt}: the flinch, on its own bone.</li>
 * </ul>
 * Clip speeds never change (GeckoLib rescales a clip's whole elapsed time with its speed, so it would jump).
 */
public final class StinkflyAnimatable implements GeoReplacedEntity {
	public static final StinkflyAnimatable INSTANCE = new StinkflyAnimatable();

	private static final String P = "animation.projecthero.stinkfly.";
	private static final RawAnimation IDLE = RawAnimation.begin().thenLoop(P + "idle");
	private static final RawAnimation WALK = RawAnimation.begin().thenLoop(P + "walk");
	private static final RawAnimation HOVER = RawAnimation.begin().thenLoop(P + "hover");
	private static final RawAnimation FLY = RawAnimation.begin().thenLoop(P + "fly");
	private static final RawAnimation DIVE = RawAnimation.begin().thenPlayAndHold(P + "dive");
	private static final RawAnimation DASH = RawAnimation.begin().thenPlay(P + "dash");
	private static final RawAnimation TAKEOFF = RawAnimation.begin().thenPlay(P + "takeoff");
	private static final RawAnimation SPLASH = RawAnimation.begin().thenPlay(P + "splash");
	private static final RawAnimation LIFT = RawAnimation.begin().thenPlay(P + "lift");
	private static final RawAnimation LIFT_HOLD = RawAnimation.begin().thenLoop(P + "lift_hold");
	private static final RawAnimation SHOT = RawAnimation.begin().thenPlay(P + "shot");
	private static final RawAnimation BARRAGE = RawAnimation.begin().thenPlay(P + "barrage");
	private static final RawAnimation NET = RawAnimation.begin().thenPlay(P + "net");
	private static final RawAnimation GAS = RawAnimation.begin().thenPlay(P + "gas");
	private static final RawAnimation STAB = RawAnimation.begin().thenPlay(P + "stab");
	private static final RawAnimation JAB = RawAnimation.begin().thenPlay(P + "jab");
	private static final RawAnimation GUST = RawAnimation.begin().thenPlay(P + "gust");
	private static final RawAnimation STORM = RawAnimation.begin().thenPlay(P + "storm");
	private static final RawAnimation WINGS_FOLD = RawAnimation.begin().thenLoop(P + "wings_fold");
	private static final RawAnimation WINGS_WALK = RawAnimation.begin().thenLoop(P + "wings_walk");
	private static final RawAnimation WINGS_HOVER = RawAnimation.begin().thenLoop(P + "wings_hover");
	private static final RawAnimation WINGS_FLY = RawAnimation.begin().thenLoop(P + "wings_fly");
	private static final RawAnimation WINGS_DIVE = RawAnimation.begin().thenLoop(P + "wings_dive");
	private static final RawAnimation WINGS_GUST = RawAnimation.begin().thenPlay(P + "wings_gust");
	private static final RawAnimation JAB_R = RawAnimation.begin().thenPlay(P + "jab_r");
	private static final RawAnimation JAB_L = RawAnimation.begin().thenPlay(P + "jab_l");
	private static final RawAnimation HURT = RawAnimation.begin().thenPlay(P + "hurt");

	/** Ticks each move clip owns its bones after its synced start (the clip's length + 1). */
	public static int oneShotTicks(int animId) {
		return switch (animId) {
			case StinkflyKit.ANIM_SHOT -> 10;
			case StinkflyKit.ANIM_BARRAGE -> 11;
			case StinkflyKit.ANIM_NET -> 16;
			case StinkflyKit.ANIM_GAS -> 25;
			case StinkflyKit.ANIM_STAB -> 13;
			case StinkflyKit.ANIM_JAB -> 8;
			case StinkflyKit.ANIM_GUST -> 15;
			case StinkflyKit.ANIM_STORM -> 27;
			case StinkflyKit.ANIM_DASH, StinkflyKit.ANIM_TAKEOFF, StinkflyKit.ANIM_SPLASH -> 15;
			case StinkflyKit.ANIM_LIFT -> 13;
			default -> 0;
		};
	}

	/** The body (main controller) move clip for {@code animId}, or null. */
	private static RawAnimation bodyMove(int animId) {
		return switch (animId) {
			case StinkflyKit.ANIM_DASH -> DASH;
			case StinkflyKit.ANIM_TAKEOFF -> TAKEOFF;
			case StinkflyKit.ANIM_SPLASH -> SPLASH;
			case StinkflyKit.ANIM_LIFT -> LIFT;
			default -> null;
		};
	}

	/** The upper-body (move controller) clip for {@code animId}, or null. */
	private static RawAnimation upperMove(int animId) {
		return switch (animId) {
			case StinkflyKit.ANIM_SHOT -> SHOT;
			case StinkflyKit.ANIM_BARRAGE -> BARRAGE;
			case StinkflyKit.ANIM_NET -> NET;
			case StinkflyKit.ANIM_GAS -> GAS;
			case StinkflyKit.ANIM_STAB -> STAB;
			case StinkflyKit.ANIM_JAB -> JAB;
			case StinkflyKit.ANIM_GUST -> GUST;
			case StinkflyKit.ANIM_STORM -> STORM;
			default -> null;
		};
	}

	/** Client render thread only: per player, the move start each controller last played / the swing side. */
	private static final Map<Player, Long> LAST_BODY = new WeakHashMap<>();
	private static final Map<Player, Long> LAST_MOVE = new WeakHashMap<>();
	private static final Map<Player, Long> LAST_WINGS = new WeakHashMap<>();
	private static final Map<Player, boolean[]> SWING = new WeakHashMap<>();

	private final AnimatableInstanceCache cache = GeckoLibUtil.createInstanceCache(this);

	private StinkflyAnimatable() {
	}

	@Override
	public EntityType<?> getReplacingEntityType() {
		return EntityType.PLAYER;
	}

	@Override
	public void registerControllers(AnimatableManager.ControllerRegistrar controllers) {
		controllers.add(new AnimationController<>(this, "main", 4, this::main));
		controllers.add(new AnimationController<>(this, "move", 2, this::move));
		controllers.add(new AnimationController<>(this, "wings", 3, this::wings));
		controllers.add(new AnimationController<>(this, "swing", 2, this::swing));
		controllers.add(new AnimationController<>(this, "hurt", 1, this::hurt));
	}

	/** In the air on his wings: the server's synced flying flag (a remote player's onGround is not reliable). */
	public static boolean flying(Player p) {
		return (Omnitrix.state(p).kitFlags & StinkflyKit.F_FLYING) != 0;
	}

	public static boolean diving(Player p) {
		return (Omnitrix.state(p).kitFlags & StinkflyKit.F_DIVING) != 0;
	}

	public static boolean lifting(Player p) {
		return (Omnitrix.state(p).kitFlags & StinkflyKit.F_LIFT) != 0;
	}

	private static double speed(Player p) {
		double dx = p.getX() - p.xo, dy = p.getY() - p.yo, dz = p.getZ() - p.zo;
		return Math.sqrt(dx * dx + dy * dy + dz * dz);
	}

	private static double groundSpeed(Player p) {
		double dx = p.getX() - p.xo, dz = p.getZ() - p.zo;
		return Math.sqrt(dx * dx + dz * dz);
	}

	/** The synced move playing right now (its id), or 0. */
	private static int playing(Player p) {
		OmnitrixState s = Omnitrix.state(p);
		long since = p.level().getGameTime() - s.animStart;
		int len = oneShotTicks(s.animId);
		return len > 0 && since >= 0 && since < len ? s.animId : 0;
	}

	/** A fresh start of the same move again: from the top. */
	private static void restartOnNew(AnimationState<StinkflyAnimatable> state, Map<Player, Long> last, Player p) {
		long start = Omnitrix.state(p).animStart;
		Long was = last.get(p);
		if (was != null && was != start) {
			state.getController().forceAnimationReset();
		}
		last.put(p, start);
	}

	private PlayState main(AnimationState<StinkflyAnimatable> state) {
		if (!(state.getData(DataTickets.ENTITY) instanceof Player p) || !Omnitrix.hasPower(p)) {
			return state.setAndContinue(IDLE);
		}
		if (diving(p)) {
			return state.setAndContinue(DIVE);
		}
		RawAnimation move = bodyMove(playing(p));
		if (move != null) {
			restartOnNew(state, LAST_BODY, p);
			return state.setAndContinue(move);
		}
		if (lifting(p)) {
			return state.setAndContinue(LIFT_HOLD);
		}
		if (flying(p)) {
			return state.setAndContinue(speed(p) > 0.16 ? FLY : HOVER);
		}
		return state.setAndContinue(groundSpeed(p) > 0.015 ? WALK : IDLE);
	}

	private PlayState move(AnimationState<StinkflyAnimatable> state) {
		if (!(state.getData(DataTickets.ENTITY) instanceof Player p) || !Omnitrix.hasPower(p) || diving(p)) {
			return PlayState.STOP;
		}
		RawAnimation move = upperMove(playing(p));
		if (move == null) {
			state.getController().forceAnimationReset();
			return PlayState.STOP;
		}
		restartOnNew(state, LAST_MOVE, p);
		return state.setAndContinue(move);
	}

	private PlayState wings(AnimationState<StinkflyAnimatable> state) {
		if (!(state.getData(DataTickets.ENTITY) instanceof Player p) || !Omnitrix.hasPower(p)) {
			return state.setAndContinue(WINGS_FOLD);
		}
		if (diving(p)) {
			return state.setAndContinue(WINGS_DIVE);
		}
		int id = playing(p);
		if (id == StinkflyKit.ANIM_GUST) {
			restartOnNew(state, LAST_WINGS, p);
			return state.setAndContinue(WINGS_GUST);
		}
		if (id == StinkflyKit.ANIM_DASH || id == StinkflyKit.ANIM_TAKEOFF) {
			return state.setAndContinue(WINGS_FLY);
		}
		if (flying(p) || lifting(p)) {
			return state.setAndContinue(speed(p) > 0.16 ? WINGS_FLY : WINGS_HOVER);
		}
		return state.setAndContinue(groundSpeed(p) > 0.015 ? WINGS_WALK : WINGS_FOLD);
	}

	private PlayState swing(AnimationState<StinkflyAnimatable> state) {
		if (!(state.getData(DataTickets.ENTITY) instanceof Player p) || !Omnitrix.hasPower(p)) {
			return PlayState.STOP;
		}
		int id = playing(p);
		boolean busy = diving(p) || lifting(p) || (id != 0 && id != StinkflyKit.ANIM_JAB);
		boolean[] side = SWING.computeIfAbsent(p, q -> new boolean[] { false, false }); // { swinging last frame, left next }
		if (p.swinging && !side[0]) {
			side[1] = !side[1];
			state.getController().forceAnimationReset();
		}
		side[0] = p.swinging;
		if (busy || !p.swinging) {
			if (!p.swinging) {
				state.getController().forceAnimationReset();
			}
			return PlayState.STOP;
		}
		boolean left = p.getMainArm() == HumanoidArm.LEFT ? !side[1] : side[1];
		return state.setAndContinue(left ? JAB_L : JAB_R);
	}

	private PlayState hurt(AnimationState<StinkflyAnimatable> state) {
		if (state.getData(DataTickets.ENTITY) instanceof Player p && p.hurtTime > 0) {
			if (p.hurtTime == p.hurtDuration) {
				state.getController().forceAnimationReset();
			}
			return state.setAndContinue(HURT);
		}
		state.getController().forceAnimationReset();
		return PlayState.STOP;
	}

	@Override
	public AnimatableInstanceCache getAnimatableInstanceCache() {
		return cache;
	}
}
