package com.projecthero.mod.client.quirk.darkshadow;

import com.mojang.blaze3d.vertex.PoseStack;
import com.mojang.blaze3d.vertex.VertexConsumer;
import com.mojang.math.Axis;
import com.projecthero.mod.ProjectHeroMod;

import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.client.renderer.texture.OverlayTexture;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.util.Mth;

/**
 * v0.16.7: the Dark Shadow creature as real 3D geometry (built in code, baked once, no model-layer registration): a big
 * beaked bird head (skull, hooked beak, opening jaw, swept-back crest, cheek ruffs, glowing eyes, berserk spikes), the
 * tendril segment its neck and arms are drawn from, clawed hands, and the feathered wings of Black Fallen Angel. Texture:
 * {@code textures/entity/quirk/dark_shadow/creature.png} (generated by {@code scratchpad/gen_dark_shadow.js}).
 *
 * <p>The head and the wings use the vanilla entity convention (call {@link #flip} first: y down, the face toward -z,
 * +x the creature's left). {@link #segment} / {@link #claw} are drawn along +z of the current pose, unflipped.
 */
public final class DarkShadowModel {
	public static final ResourceLocation TEXTURE = ProjectHeroMod.id("textures/entity/quirk/dark_shadow/creature.png");

	private static ModelPart skull, beak, tip, jaw, eyeL, eyeR, crestMid, crestL, crestR, ruffL, ruffR;
	private static ModelPart segment, claw, hand, spike, wingBone, feather;

	private DarkShadowModel() {
	}

	private static void build() {
		MeshDefinition mesh = new MeshDefinition();
		PartDefinition r = mesh.getRoot();
		r.addOrReplaceChild("skull", CubeListBuilder.create().texOffs(0, 0).addBox(-4f, -3.5f, -4f, 8f, 7f, 8f), PartPose.ZERO);
		r.addOrReplaceChild("beak", CubeListBuilder.create().texOffs(32, 0).addBox(-2f, -1f, -10f, 4f, 3f, 6f), PartPose.ZERO);
		r.addOrReplaceChild("tip", CubeListBuilder.create().texOffs(52, 0).addBox(-1f, 0f, -12f, 2f, 3f, 3f), PartPose.ZERO);
		r.addOrReplaceChild("jaw", CubeListBuilder.create().texOffs(32, 10).addBox(-1.5f, 0f, -5f, 3f, 2f, 5f), PartPose.offset(0f, 2f, -4f));
		r.addOrReplaceChild("eye_l", CubeListBuilder.create().texOffs(52, 7).addBox(-1f, -0.5f, -0.5f, 2f, 1f, 1f),
				PartPose.offsetAndRotation(2.4f, -1.4f, -4.1f, 0f, 0f, 0.32f));
		r.addOrReplaceChild("eye_r", CubeListBuilder.create().texOffs(52, 7).addBox(-1f, -0.5f, -0.5f, 2f, 1f, 1f),
				PartPose.offsetAndRotation(-2.4f, -1.4f, -4.1f, 0f, 0f, -0.32f));
		r.addOrReplaceChild("crest_mid", CubeListBuilder.create().texOffs(0, 16).addBox(-1f, -5f, 0f, 2f, 5f, 6f),
				PartPose.offsetAndRotation(0f, -2.5f, -2f, -0.55f, 0f, 0f));
		r.addOrReplaceChild("crest_l", CubeListBuilder.create().texOffs(0, 16).addBox(-1f, -5f, 0f, 2f, 5f, 6f),
				PartPose.offsetAndRotation(2.5f, -2.5f, -1f, -0.75f, 0.4f, 0.2f));
		r.addOrReplaceChild("crest_r", CubeListBuilder.create().texOffs(0, 16).addBox(-1f, -5f, 0f, 2f, 5f, 6f),
				PartPose.offsetAndRotation(-2.5f, -2.5f, -1f, -0.75f, -0.4f, -0.2f));
		r.addOrReplaceChild("ruff_l", CubeListBuilder.create().texOffs(16, 16).addBox(0f, -1f, -1f, 1f, 6f, 5f),
				PartPose.offsetAndRotation(3.6f, -0.5f, -1.5f, 0.35f, 0.35f, -0.35f));
		r.addOrReplaceChild("ruff_r", CubeListBuilder.create().texOffs(16, 16).mirror().addBox(-1f, -1f, -1f, 1f, 6f, 5f),
				PartPose.offsetAndRotation(-3.6f, -0.5f, -1.5f, 0.35f, -0.35f, 0.35f));
		r.addOrReplaceChild("segment", CubeListBuilder.create().texOffs(0, 28).addBox(-2f, -2f, 0f, 4f, 4f, 16f), PartPose.ZERO);
		r.addOrReplaceChild("claw", CubeListBuilder.create().texOffs(40, 28).addBox(-0.5f, -0.5f, 0f, 1f, 1f, 4f), PartPose.ZERO);
		r.addOrReplaceChild("hand", CubeListBuilder.create().texOffs(40, 34).addBox(-1.5f, -1.5f, -1.5f, 3f, 3f, 3f), PartPose.ZERO);
		r.addOrReplaceChild("spike", CubeListBuilder.create().texOffs(52, 28).addBox(-0.5f, -0.5f, 0f, 1f, 1f, 5f), PartPose.ZERO);
		r.addOrReplaceChild("wing_bone", CubeListBuilder.create().texOffs(0, 48).addBox(0f, -1f, -1f, 16f, 2f, 2f), PartPose.ZERO);
		r.addOrReplaceChild("feather", CubeListBuilder.create().texOffs(36, 48).addBox(-1.5f, 0f, -0.5f, 3f, 12f, 1f), PartPose.ZERO);
		ModelPart root = LayerDefinition.create(mesh, 64, 64).bakeRoot();
		skull = root.getChild("skull");
		beak = root.getChild("beak");
		tip = root.getChild("tip");
		jaw = root.getChild("jaw");
		eyeL = root.getChild("eye_l");
		eyeR = root.getChild("eye_r");
		crestMid = root.getChild("crest_mid");
		crestL = root.getChild("crest_l");
		crestR = root.getChild("crest_r");
		ruffL = root.getChild("ruff_l");
		ruffR = root.getChild("ruff_r");
		segment = root.getChild("segment");
		claw = root.getChild("claw");
		hand = root.getChild("hand");
		spike = root.getChild("spike");
		wingBone = root.getChild("wing_bone");
		feather = root.getChild("feather");
	}

	private static void ensure() {
		if (skull == null) {
			build();
		}
	}

	/** Into the vanilla entity frame for a creature facing {@code yawDeg} (Minecraft yaw: 0 = +z). */
	public static void flip(PoseStack pose, float yawDeg) {
		pose.mulPose(Axis.YP.rotationDegrees(180f - yawDeg));
		pose.scale(-1f, -1f, 1f);
	}

	/**
	 * The head at the pose's origin (already {@link #flip}ped and scaled): {@code pitch} radians nose-down, the jaw open
	 * {@code jawOpen} radians, {@code spikes} 0..1 how much of the berserk spike crown shows.
	 */
	public static void head(PoseStack pose, VertexConsumer vc, int light, float pitch, float jawOpen, float spikes, int argb) {
		ensure();
		pose.pushPose();
		pose.mulPose(Axis.XP.rotation(pitch));
		int o = OverlayTexture.NO_OVERLAY;
		skull.render(pose, vc, light, o, argb);
		beak.render(pose, vc, light, o, argb);
		tip.render(pose, vc, light, o, argb);
		jaw.xRot = jawOpen;
		jaw.render(pose, vc, light, o, argb);
		crestMid.render(pose, vc, light, o, argb);
		crestL.render(pose, vc, light, o, argb);
		crestR.render(pose, vc, light, o, argb);
		ruffL.render(pose, vc, light, o, argb);
		ruffR.render(pose, vc, light, o, argb);
		if (spikes > 0.02f) {
			// a crown of spikes bursting from the back of the skull, longer the wilder it is
			for (int i = 0; i < 7; i++) {
				float a = (i - 3) * 0.42f;
				pose.pushPose();
				pose.translate(Mth.sin(a) * 3.5f / 16f, (-2.5f + Math.abs(i - 3) * 0.8f) / 16f, 3f / 16f);
				pose.mulPose(Axis.YP.rotation(a * 0.9f));
				pose.mulPose(Axis.XP.rotation(-0.5f + Math.abs(i - 3) * 0.12f));
				float len = spikes * (0.9f + 0.25f * ((i * 7) % 3));
				pose.scale(1f, 1f, len);
				spike.render(pose, vc, light, o, argb);
				pose.popPose();
			}
		}
		pose.popPose();
	}

	/** The glowing eyes only (draw with an emissive render type, same transform as {@link #head}). */
	public static void eyes(PoseStack pose, VertexConsumer vc, float pitch, int argb) {
		ensure();
		pose.pushPose();
		pose.mulPose(Axis.XP.rotation(pitch));
		eyeL.render(pose, vc, 0xF000F0, OverlayTexture.NO_OVERLAY, argb);
		eyeR.render(pose, vc, 0xF000F0, OverlayTexture.NO_OVERLAY, argb);
		pose.popPose();
	}

	/** One tendril segment from the pose origin along +z: {@code length} blocks long, {@code thick} blocks across. */
	public static void segment(PoseStack pose, VertexConsumer vc, int light, float length, float thick, int argb) {
		ensure();
		pose.pushPose();
		float w = thick / 0.25f;
		pose.scale(w, w, length);
		segment.render(pose, vc, light, OverlayTexture.NO_OVERLAY, argb);
		pose.popPose();
	}

	/** A clawed hand at the pose origin, fingers along +z; {@code curl} 0 (open) .. 1 (clenched), {@code size} blocks per 16 px. */
	public static void claw(PoseStack pose, VertexConsumer vc, int light, float curl, float size, int argb) {
		ensure();
		pose.pushPose();
		pose.scale(size, size, size);
		int o = OverlayTexture.NO_OVERLAY;
		hand.render(pose, vc, light, o, argb);
		for (int i = 0; i < 3; i++) {
			pose.pushPose();
			float spread = (i - 1) * 0.45f;
			pose.translate((i - 1) * 1.0f / 16f, 0f, 1.2f / 16f);
			pose.mulPose(Axis.YP.rotation(spread * (1f - curl * 0.6f)));
			pose.mulPose(Axis.XP.rotation(0.3f + curl * 0.9f));
			pose.scale(1f, 1f, 1.3f);
			claw.render(pose, vc, light, o, argb);
			pose.popPose();
		}
		// the thumb claw
		pose.pushPose();
		pose.translate(0f, -1.2f / 16f, 0.8f / 16f);
		pose.mulPose(Axis.XP.rotation(-0.6f - curl * 0.5f));
		claw.render(pose, vc, light, o, argb);
		pose.popPose();
		pose.popPose();
	}

	/** A spike from the pose origin along +z, {@code len} times its 5 px. */
	public static void spike(PoseStack pose, VertexConsumer vc, int light, float len, int argb) {
		ensure();
		pose.pushPose();
		pose.scale(1f, 1f, len);
		spike.render(pose, vc, light, OverlayTexture.NO_OVERLAY, argb);
		pose.popPose();
	}

	/**
	 * One wing in the flipped body frame, rooted at the pose origin: {@code side} +1 the creature's left (+x), -1 its right;
	 * {@code sweep} radians the whole wing turns forward (+) or back about the vertical, {@code lift} radians it is raised,
	 * {@code fan} 0 (folded) .. 1 (feathers fanned out).
	 */
	public static void wing(PoseStack pose, VertexConsumer vc, int light, int side, float sweep, float lift, float fan, int argb) {
		ensure();
		int o = OverlayTexture.NO_OVERLAY;
		pose.pushPose();
		if (side < 0) {
			pose.scale(-1f, 1f, 1f); // mirrored (the cutout no-cull render type draws both faces)
		}
		pose.mulPose(Axis.YP.rotation(sweep));
		pose.mulPose(Axis.ZP.rotation(-lift));
		wingBone.render(pose, vc, light, o, argb);
		for (int i = 0; i < 6; i++) {
			pose.pushPose();
			pose.translate((1.5f + i * 2.8f) / 16f, 0.5f / 16f, 0f);
			pose.mulPose(Axis.ZP.rotation(-(0.05f + i * 0.17f) * fan));
			pose.mulPose(Axis.XP.rotation(0.12f));
			pose.scale(1f, 0.7f + i * 0.14f, 1f);
			feather.render(pose, vc, light, o, argb);
			pose.popPose();
		}
		// the claw on the wing's leading edge
		pose.pushPose();
		pose.translate(16f / 16f, 0f, 0f);
		pose.mulPose(Axis.YP.rotation(-1.2f));
		spike.render(pose, vc, light, o, argb);
		pose.popPose();
		pose.popPose();
	}
}
