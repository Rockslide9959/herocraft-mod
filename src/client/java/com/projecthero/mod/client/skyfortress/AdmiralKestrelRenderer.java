package com.projecthero.mod.client.skyfortress;

import com.projecthero.mod.ProjectHeroMod;
import com.projecthero.mod.skyfortress.entity.AdmiralKestrelBoss;

import net.minecraft.client.renderer.entity.EntityRendererProvider;
import net.minecraft.resources.ResourceLocation;

import software.bernie.geckolib.model.GeoModel;
import software.bernie.geckolib.renderer.GeoEntityRenderer;
import software.bernie.geckolib.renderer.layer.AutoGlowingGeoLayer;

/**
 * v0.17.7: draws Admiral Kestrel through GeckoLib -- {@code geo/admiral_kestrel.geo.json}, its texture and glowmask
 * (visor, thruster cores, pod lights, wing-edge strips burn in the dark) and its clips, all generated by
 * {@code scratchpad/v0177/gen_kestrel.js}. No vanilla tip-over on death: the death clip crumples her.
 */
public class AdmiralKestrelRenderer extends GeoEntityRenderer<AdmiralKestrelBoss> {
	public AdmiralKestrelRenderer(EntityRendererProvider.Context context) {
		super(context, new Model());
		this.shadowRadius = 0.9f;
		addRenderLayer(new AutoGlowingGeoLayer<>(this));
	}

	static final class Model extends GeoModel<AdmiralKestrelBoss> {
		private static final ResourceLocation MODEL = ProjectHeroMod.id("geo/admiral_kestrel.geo.json");
		private static final ResourceLocation TEXTURE = ProjectHeroMod.id("textures/entity/admiral_kestrel.png");
		private static final ResourceLocation ANIMATION = ProjectHeroMod.id("animations/admiral_kestrel.animation.json");

		@Override
		public ResourceLocation getModelResource(AdmiralKestrelBoss animatable) {
			return MODEL;
		}

		@Override
		public ResourceLocation getTextureResource(AdmiralKestrelBoss animatable) {
			return TEXTURE;
		}

		@Override
		public ResourceLocation getAnimationResource(AdmiralKestrelBoss animatable) {
			return ANIMATION;
		}
	}

	@Override
	protected float getDeathMaxRotation(AdmiralKestrelBoss animatable) {
		return 0.0f;
	}
}
