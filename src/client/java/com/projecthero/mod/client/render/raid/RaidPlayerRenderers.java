/**
 * v0.16.1: the Armoured Risen, the Acid Zombie, the Juggernaut, the Cursed Zombie, the Sword Skeleton and the Pillager Spy
 * (the basic / baby Risen keep the vanilla zombie look, {@link RaidZombieDispatchRenderer}) on the standard <b>player rig</b> (head, body,
 * arms, legs and the hat / jacket / sleeve / pants outer layers) with their own detailed 64x64 skins
 * ({@code textures/entity/raid_skin/<name>.png}, generated by {@code scratchpad/gen_raid_player_skins.js}), plus a
 * full-bright emissive layer ({@code <name>_glow.png}, {@link RenderType#eyes}) for the glowing parts -- eyes, acid sacs,
 * Gravebound runes, the Juggernaut's mask slits.
 * <ul>
 *   <li>Zombies (Armoured Risen, Acid, Juggernaut, Cursed): the vanilla zombie arm animation (arms raised while aggressive,
 *       the attack swing) on the player rig; a baby is the player model at baby scale; the Juggernaut keeps its larger
 *       scale.</li>
 *   <li>The Sword Skeleton: a player-proportioned body with vanilla's skeleton melee-swing pose and a raised shield while
 *       it blocks.</li>
 *   <li>The Pillager Spy: the illager crossbow hold / charge poses on the player rig.</li>
 *   <li>Held gear is real held items (sword, shield, crossbow) through the normal item-in-hand layer; worn armour through
 *       the normal armour layer -- except the Armoured Risen, whose rusted kit is painted into its skin.</li>
 * </ul>
 * Only these mod entity types use these renderers; the vanilla zombie, baby zombie and every other vanilla mob are untouched.
 */
public final class RaidPlayerRenderers {
	private RaidPlayerRenderers() {
	}

	/** v0.16.7 (perf): asked for every frame by the renderers -- built once per name. */
	private static final java.util.Map<String, ResourceLocation> SKIN_CACHE = new java.util.concurrent.ConcurrentHashMap<>();

	public static ResourceLocation skin(String name) {
		return SKIN_CACHE.computeIfAbsent(name, k -> ProjectHeroMod.id("textures/entity/raid_skin/" + k + ".png"));
	}

	/** v0.16.7 (perf): asked for every frame by the renderers -- built once per name. */
	private static final java.util.Map<String, ResourceLocation> GLOW_CACHE = new java.util.concurrent.ConcurrentHashMap<>();

	public static ResourceLocation glow(String name) {
		return GLOW_CACHE.computeIfAbsent(name, k -> ProjectHeroMod.id("textures/entity/raid_skin/" + k + "_glow.png"));
	}

	// ---------------------------------------------------------------- models

	/** The player rig with vanilla's zombie arms (raised while aggressive, the attack swing). */
	public static class ZombiePlayerModel<T extends Mob> extends PlayerModel<T> {
		public ZombiePlayerModel(ModelPart root) {
			super(root, false);
		}

		@Override
		public void setupAnim(T mob, float limbSwing, float limbSwingAmount, float ageInTicks, float netHeadYaw, float headPitch) {
			super.setupAnim(mob, limbSwing, limbSwingAmount, ageInTicks, netHeadYaw, headPitch);
			AnimationUtils.animateZombieArms(this.leftArm, this.rightArm, mob.isAggressive(), this.attackTime, ageInTicks);
			syncOuter(this);
		}
	}

	/** The player rig with the skeleton's melee pose (vanilla SkeletonModel's sword swing) and a shield block. */
	public static class SkeletonPlayerModel extends PlayerModel<SwordSkeleton> {
		public SkeletonPlayerModel(ModelPart root) {
			super(root, false);
		}

		@Override
		public void prepareMobModel(SwordSkeleton mob, float limbSwing, float limbSwingAmount, float partialTick) {
			this.rightArmPose = HumanoidModel.ArmPose.EMPTY;
			this.leftArmPose = mob.isUsingItem() && mob.getOffhandItem().is(Items.SHIELD) ? HumanoidModel.ArmPose.BLOCK : HumanoidModel.ArmPose.EMPTY;
			super.prepareMobModel(mob, limbSwing, limbSwingAmount, partialTick);
		}

		@Override
		public void setupAnim(SwordSkeleton mob, float limbSwing, float limbSwingAmount, float ageInTicks, float netHeadYaw, float headPitch) {
			super.setupAnim(mob, limbSwing, limbSwingAmount, ageInTicks, netHeadYaw, headPitch);
			if (mob.isAggressive() && !mob.getMainHandItem().is(Items.BOW)) {
				// vanilla SkeletonModel: both arms forward, the swing driven by attackTime
				float f = Mth.sin(this.attackTime * Mth.PI);
				float g = Mth.sin((1.0F - (1.0F - this.attackTime) * (1.0F - this.attackTime)) * Mth.PI);
				this.rightArm.zRot = 0.0F;
				this.rightArm.yRot = -(0.1F - f * 0.6F);
				this.rightArm.xRot = -Mth.HALF_PI - (f * 1.2F - g * 0.4F);
				boolean blocking = this.leftArmPose == HumanoidModel.ArmPose.BLOCK;
				if (!blocking) {
					this.leftArm.zRot = 0.0F;
					this.leftArm.yRot = 0.1F - f * 0.6F;
					this.leftArm.xRot = -Mth.HALF_PI - (f * 1.2F - g * 0.4F);
				}
				AnimationUtils.bobModelPart(this.rightArm, ageInTicks, 1.0F);
				if (!blocking) {
					AnimationUtils.bobModelPart(this.leftArm, ageInTicks, -1.0F);
				}
			}
			syncOuter(this);
		}
	}

	/** The player rig with the illager crossbow poses. */
	public static class IllagerPlayerModel<T extends AbstractIllager> extends PlayerModel<T> {
		public IllagerPlayerModel(ModelPart root) {
			super(root, false);
		}

		@Override
		public void setupAnim(T mob, float limbSwing, float limbSwingAmount, float ageInTicks, float netHeadYaw, float headPitch) {
			super.setupAnim(mob, limbSwing, limbSwingAmount, ageInTicks, netHeadYaw, headPitch);
			switch (mob.getArmPose()) {
				case CROSSBOW_HOLD -> AnimationUtils.animateCrossbowHold(this.rightArm, this.leftArm, this.head, true);
				case CROSSBOW_CHARGE -> AnimationUtils.animateCrossbowCharge(this.rightArm, this.leftArm, mob, true);
				case ATTACKING -> AnimationUtils.swingWeaponDown(this.rightArm, this.leftArm, mob, this.attackTime, ageInTicks);
				default -> {
				}
			}
			syncOuter(this);
		}
	}

	/** The outer layer follows the posed limbs (PlayerModel copies them before our pose changes). */
	static void syncOuter(PlayerModel<?> m) {
		m.leftSleeve.copyFrom(m.leftArm);
		m.rightSleeve.copyFrom(m.rightArm);
		m.leftPants.copyFrom(m.leftLeg);
		m.rightPants.copyFrom(m.rightLeg);
		m.jacket.copyFrom(m.body);
		m.hat.copyFrom(m.head);
	}

	// ---------------------------------------------------------------- the full-bright glow layer

	/** Eyes-style emissive pass of the skin's {@code _glow.png} (black = nothing; the rest full-bright). */
	public static class GlowLayer<T extends LivingEntity, M extends PlayerModel<T>> extends RenderLayer<T, M> {
		private final Function<T, ResourceLocation> texture;

		public GlowLayer(RenderLayerParent<T, M> parent, Function<T, ResourceLocation> texture) {
			super(parent);
			this.texture = texture;
		}

		@Override
		public void render(PoseStack poseStack, MultiBufferSource buffers, int light, T mob, float limbSwing, float limbSwingAmount, float partialTick,
				float ageInTicks, float netHeadYaw, float headPitch) {
			if (mob.isInvisible()) {
				return;
			}
			getParentModel().renderToBuffer(poseStack, buffers.getBuffer(RenderType.eyes(texture.apply(mob))), 0xF00000, OverlayTexture.NO_OVERLAY);
		}
	}

	// ---------------------------------------------------------------- renderers

	/** Any raid zombie on the player rig: per-entity skin, an optional scale (the Juggernaut), glow, armour layer. */
	public static class ZombieRenderer<T extends Zombie> extends HumanoidMobRenderer<T, ZombiePlayerModel<T>> {
		private final Function<T, String> name;
		private final float scale;

		public ZombieRenderer(EntityRendererProvider.Context context, Function<T, String> name, float scale) {
			super(context, new ZombiePlayerModel<>(context.bakeLayer(ModelLayers.PLAYER)), 0.5f * scale);
			this.name = name;
			this.scale = scale;
			addLayer(new HumanoidArmorLayer<>(this, new HumanoidArmorModel<>(context.bakeLayer(ModelLayers.PLAYER_INNER_ARMOR)),
					new HumanoidArmorModel<>(context.bakeLayer(ModelLayers.PLAYER_OUTER_ARMOR)), context.getModelManager()) {
				@Override
				public void render(PoseStack poseStack, MultiBufferSource buffers, int light, T mob, float limbSwing, float limbSwingAmount, float partialTick,
						float ageInTicks, float netHeadYaw, float headPitch) {
					if (mob instanceof RaidZombie z && z.variant() == RaidZombie.Variant.ARMOURED) {
						return; // its rusted kit is painted into the skin's outer layer
					}
					super.render(poseStack, buffers, light, mob, limbSwing, limbSwingAmount, partialTick, ageInTicks, netHeadYaw, headPitch);
				}
			});
			addLayer(new GlowLayer<>(this, m -> glow(this.name.apply(m))));
		}

		@Override
		public ResourceLocation getTextureLocation(T mob) {
			return skin(name.apply(mob));
		}

		@Override
		protected void scale(T mob, PoseStack poseStack, float partialTick) {
			super.scale(mob, poseStack, partialTick);
			if (scale != 1.0f) {
				poseStack.scale(scale, scale, scale);
			}
		}
	}

	public static class SkeletonRenderer extends HumanoidMobRenderer<SwordSkeleton, SkeletonPlayerModel> {
		public SkeletonRenderer(EntityRendererProvider.Context context) {
			super(context, new SkeletonPlayerModel(context.bakeLayer(ModelLayers.PLAYER)), 0.5f);
			addLayer(new HumanoidArmorLayer<>(this, new HumanoidArmorModel<>(context.bakeLayer(ModelLayers.PLAYER_INNER_ARMOR)),
					new HumanoidArmorModel<>(context.bakeLayer(ModelLayers.PLAYER_OUTER_ARMOR)), context.getModelManager()));
			addLayer(new GlowLayer<>(this, m -> glow("sword_skeleton")));
		}

		@Override
		public ResourceLocation getTextureLocation(SwordSkeleton mob) {
			return skin("sword_skeleton");
		}
	}

	public static class SpyRenderer extends HumanoidMobRenderer<PillagerSpy, IllagerPlayerModel<PillagerSpy>> {
		public SpyRenderer(EntityRendererProvider.Context context) {
			super(context, new IllagerPlayerModel<>(context.bakeLayer(ModelLayers.PLAYER)), 0.5f);
			addLayer(new GlowLayer<>(this, m -> glow("pillager_spy")));
		}

		@Override
		public ResourceLocation getTextureLocation(PillagerSpy mob) {
			return skin("pillager_spy");
		}
	}
}
