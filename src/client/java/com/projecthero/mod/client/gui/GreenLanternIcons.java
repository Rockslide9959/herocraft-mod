package com.projecthero.mod.client.gui;

import java.util.Locale;
import java.util.Map;
import java.util.concurrent.ConcurrentHashMap;

import com.mojang.blaze3d.systems.RenderSystem;
import com.projecthero.mod.ProjectHeroMod;
import com.projecthero.mod.greenlantern.bind.GreenLanternBinding.Entry;

import net.minecraft.client.Minecraft;
import net.minecraft.client.gui.GuiGraphics;
import net.minecraft.resources.ResourceLocation;

/**
 * v0.17.1 Construct Menu v2: the 32x32 hard-light icons, one PNG per catalogue entry, looked up by name so a new
 * entry needs no code here -- drop {@code textures/gui/green_lantern/icons/<entry id>.png} in and it is used (entry id =
 * the {@link Entry#id()}, e.g. {@code construct_fist}, {@code c_buzzsaw}). An entry without its own file gets the
 * generic hard-light tile. Variant icons (e.g. the Carry Platform's car / jet forms) use the same lookup by name:
 * {@code c_carry_platform_car}, {@code c_carry_platform_jet}. Generated by {@code scratchpad/gl_icons_v0171/make_icons.js}.
 */
public final class GreenLanternIcons {
	public static final String DIR = "textures/gui/green_lantern/icons/";
	public static final ResourceLocation GENERIC = ProjectHeroMod.id(DIR + "_generic.png");
	/** The Lantern Corps symbol ({@link #EMBLEM_SIZE} px square, pale), drawn faintly behind the menu. */
	public static final ResourceLocation EMBLEM = ProjectHeroMod.id(DIR + "_emblem.png");
	public static final int EMBLEM_SIZE = 128;

	private static final Map<String, ResourceLocation> CACHE = new ConcurrentHashMap<>();

	private GreenLanternIcons() {
	}

	/** The icon texture for a name (an entry id or a variant id), or {@link #GENERIC} when there is no such file. */
	public static ResourceLocation of(String name) {
		if (name == null || name.isEmpty()) {
			return GENERIC;
		}
		return CACHE.computeIfAbsent(name.toLowerCase(Locale.ROOT), n -> {
			ResourceLocation rl = ProjectHeroMod.id(DIR + n + ".png");
			try {
				return Minecraft.getInstance().getResourceManager().getResource(rl).isPresent() ? rl : GENERIC;
			} catch (RuntimeException e) {
				return GENERIC;
			}
		});
	}

	public static ResourceLocation of(Entry e) {
		return e == null ? GENERIC : of(e.id());
	}

	/** Forgets the lookups (resource packs may have changed). */
	public static void clearCache() {
		CACHE.clear();
	}

	/**
	 * Draws {@code tex} (a 32x32 icon) at {@code size} GUI px, tinted by {@code argb} on top of whatever shader colour is
	 * already set (so a screen's fade-in still applies), which is put back afterwards.
	 */
	public static void draw(GuiGraphics g, ResourceLocation tex, int x, int y, int size, int argb) {
		draw(g, tex, x, y, size, size, 32, argb);
	}

	/** Draws a square texture of {@code texSize} px at {@code w} x {@code h} GUI px (the emblem uses it). */
	public static void draw(GuiGraphics g, ResourceLocation tex, int x, int y, int w, int h, int texSize, int argb) {
		g.flush();
		float[] was = RenderSystem.getShaderColor().clone();
		RenderSystem.enableBlend();
		RenderSystem.defaultBlendFunc();
		RenderSystem.setShaderColor(was[0] * ((argb >> 16) & 0xFF) / 255f, was[1] * ((argb >> 8) & 0xFF) / 255f,
				was[2] * (argb & 0xFF) / 255f, was[3] * ((argb >>> 24) & 0xFF) / 255f);
		g.blit(tex, x, y, w, h, 0f, 0f, texSize, texSize, texSize, texSize);
		RenderSystem.setShaderColor(was[0], was[1], was[2], was[3]);
		RenderSystem.disableBlend();
	}

	public static void draw(GuiGraphics g, Entry e, int x, int y, int size) {
		draw(g, of(e), x, y, size, 0xFFFFFFFF);
	}
}
