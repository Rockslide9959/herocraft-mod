package com.projecthero.mod.client.gui;

import com.projecthero.mod.ProjectHeroMod;
import com.projecthero.mod.ironman.IronManEnergy;
import com.projecthero.mod.ironman.fabricator.IronManSuitPlatformBlockEntity;
import com.projecthero.mod.ironman.fabricator.IronManSuitPlatformMenu;
import com.projecthero.mod.ironman.item.IronManArmorItem;
import com.projecthero.mod.ironman.suit.IronManSuit;
import com.projecthero.mod.ironman.suit.IronManSuits;
import com.projecthero.mod.ironman.ui.IronManUiLayout;

import net.minecraft.client.gui.GuiGraphics;
import net.minecraft.client.gui.screens.inventory.AbstractContainerScreen;
import net.minecraft.network.chat.Component;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.Util;
import net.minecraft.world.entity.player.Inventory;
import net.minecraft.world.item.ItemStack;

/**
 * Iron Man Suit Platform screen (v0.14.21 redesign) on a textured panel ({@code textures/gui/iron_man_suit_platform.png},
 * generated by {@code scratchpad/gen_v01421_ironman_gui.js}). Slot positions are unchanged from
 * {@link IronManSuitPlatformMenu}:
 * <pre>
 *   y 5        title
 *   x 7..48    y 18..113   rotating 3D preview of the stored suit (holo well)
 *   y 19       stored mark name (or "No suit stored")
 *   y 32       the four armour slots (empty ones show the vanilla armour silhouettes)
 *   x 136..170 y 29..51    REGEN plate (v0.14.27: the flat platform charge rate; the reserve is gone)
 *   y 57 / 65  CHARGE  label + %, Slab bar with the exact energy inside
 *   y 78 / 86  INTEGRITY label + %, Slab bar with the exact integrity inside
 *   y 97..115  v0.15.4: the Stark Gantry hint (the Deploy / Retrieve buttons are gone)
 *   y 124 / 182 player inventory / hotbar
 * </pre>
 */
public class IronManSuitPlatformScreen extends AbstractContainerScreen<IronManSuitPlatformMenu> {
	private static final ResourceLocation BG = ProjectHeroMod.id("textures/gui/iron_man_suit_platform.png");
	/** The vanilla empty-armour-slot silhouettes (block-atlas sprites, as the player inventory uses). */
	private static final ResourceLocation[] EMPTY_SLOT = {
			net.minecraft.world.inventory.InventoryMenu.EMPTY_ARMOR_SLOT_HELMET,
			net.minecraft.world.inventory.InventoryMenu.EMPTY_ARMOR_SLOT_CHESTPLATE,
			net.minecraft.world.inventory.InventoryMenu.EMPTY_ARMOR_SLOT_LEGGINGS,
			net.minecraft.world.inventory.InventoryMenu.EMPTY_ARMOR_SLOT_BOOTS };
	private static final int MX = IronManUiLayout.PLAT_METER_X;
	private static final int MW = IronManUiLayout.PLAT_METER_W;
	private final long openedAt = Util.getMillis();
	/** v0.15.6 / v0.16.7 (user): the side tab that packs the racked Era II suit into its briefcase / pack / case. */
	private IronManGui.StarkButton suitcase;

	public IronManSuitPlatformScreen(IronManSuitPlatformMenu menu, Inventory inv, Component title) {
		super(menu, inv, title);
		this.imageWidth = 176;
		this.imageHeight = 202;
		this.titleLabelX = 8;
		this.titleLabelY = 5;
	}

	// v0.15.4: no DEPLOY / RETRIEVE buttons any more -- the strip they used says where suiting up happens now (renderLabels)
	@Override
	protected void init() {
		super.init();
		// v0.16.7 (user): the Bracelets tab is gone (the Era II Mk VII / Mk VIII pack into their backpacks instead).
		// v0.15.6 -> v0.16.7 (user): a tab off the right edge of the panel (the panel has no free row) packs the racked
		// Era II suit into its carried form -- "Pack into Briefcase / Backpack / Thruster Pack / Heat Case", wrapped onto
		// two lines. On a screen too narrow for it on the right it sits off the left edge instead.
		int tabX = leftPos + imageWidth + 2 + PACK_W <= width ? leftPos + imageWidth + 2 : Math.max(0, leftPos - 2 - PACK_W);
		suitcase = new IronManGui.StarkButton(tabX, topPos + 94, PACK_W, PACK_H, Component.empty(),
				() -> click(IronManSuitPlatformMenu.SUITCASE_BUTTON)) {
			@Override
			protected void renderWidget(GuiGraphics g, int mouseX, int mouseY, float partialTick) {
				super.renderWidget(g, mouseX, mouseY, partialTick); // the frame; its own (empty) label draws nothing
				var lines = font.split(packLabel(), getWidth() - 6);
				int n = Math.min(2, lines.size());
				int ty = getY() + (getHeight() - n * 9) / 2 + 1;
				for (int i = 0; i < n; i++) {
					g.drawString(font, lines.get(i), getX() + (getWidth() - font.width(lines.get(i))) / 2, ty + i * 9,
							isHoveredOrFocused() ? 0xFFFFFFFF : IronManGui.TEXT, false);
				}
			}
		};
		suitcase.visible = menu.offersSuitcase();
		addRenderableWidget(suitcase);
	}

	/** v0.16.7 (user): size of the pack tab (two wrapped lines: "Pack into" / "Thruster Pack"). */
	public static final int PACK_W = 86;
	public static final int PACK_H = 24;

	/** v0.16.7 (user): "Pack into Backpack" etc. for the racked suit's form. */
	private Component packLabel() {
		var form = menu.packForm();
		return Component.translatable("screen.projecthero.suit_platform.pack_into", form == null
				? Component.translatable("screen.projecthero.suit_platform.suitcase")
				: Component.translatable("screen.projecthero.suit_platform.form." + form.suitId()));
	}

	private void click(int id) {
		if (minecraft != null && minecraft.gameMode != null) {
			minecraft.gameMode.handleInventoryButtonClick(menu.containerId, id);
		}
	}

	private ItemStack[] pieces() {
		ItemStack[] out = new ItemStack[4];
		for (int i = 0; i < 4; i++) {
			out[i] = menu.slots.get(i).getItem();
		}
		return out;
	}

	private String storedSuitId() {
		for (ItemStack s : pieces()) {
			if (s.getItem() instanceof IronManArmorItem a) {
				return a.suitId();
			}
		}
		return null;
	}

	@Override
	protected void renderBg(GuiGraphics g, float partialTick, int mouseX, int mouseY) {
		int x = leftPos;
		int y = topPos;
		g.blit(BG, x, y, 0, 0, imageWidth, imageHeight, 256, 256);
		for (int i = 0; i < 4; i++) {
			if (menu.slots.get(i).getItem().isEmpty()) {
				var sprite = minecraft.getTextureAtlas(net.minecraft.world.inventory.InventoryMenu.BLOCK_ATLAS).apply(EMPTY_SLOT[i]);
				g.blit(x + 53 + i * 20, y + 32, 0, 16, 16, sprite);
			}
		}
		// rotating preview of whatever is stored
		float secs = (Util.getMillis() - openedAt) / 1000f;
		IronManGui.suitPreview(g, x + 8, y + 19, x + 47, y + 112, pieces(), 180f + secs * 40f);
	}

	@Override
	protected void renderLabels(GuiGraphics g, int mouseX, int mouseY) {
		g.drawString(font, IronManGui.fit(font, title, imageWidth - 16), titleLabelX, titleLabelY, IronManGui.CYAN, false);

		String suitId = storedSuitId();
		IronManSuit suit = suitId == null ? null : IronManSuits.byId(suitId);
		Component head = menu.hasStoredSuit() && suit != null
				? Component.translatable(suit.nameKey())
				: Component.translatable("screen.projecthero.suit_platform.empty");
		g.drawString(font, IronManGui.fit(font, head, 80), MX + 1, 19, suit != null ? IronManGui.TEXT : IronManGui.TEXT_MUTED, false);

		// v0.14.27: the reserve is gone -- the plate shows the flat regen rate instead
		g.drawString(font, IronManGui.fit(font, Component.translatable("screen.projecthero.suit_platform.regen_short"), 30),
				139, 31, IronManGui.TEXT_DIM, false);
		// v0.15.20: the energy rate is the stored suit's own passive rate (a dash when empty)
		// v0.16.1: no suit energy -- the platform only repairs, so the plate shows its integrity repair rate
		// v0.16.7 (user) Era I: no Gantry in range = no repair here
		boolean eraOne = suit != null && suit.eraOne();
		boolean gantry = menu.gantryInRange();
		String rv = IronManGui.fit(font, suit == null ? "-" : eraOne && !gantry ? "0/s"
				: "+" + rate(IronManSuitPlatformBlockEntity.REGEN_INTEGRITY_PER_SECOND) + "/s", 30);
		g.drawString(font, rv, 139, 41, eraOne && !gantry ? IronManGui.TEXT_MUTED : IronManGui.CYAN, false);

		if (menu.hasStoredSuit()) {
			// v0.16.1 comic rework: integrity is the only bar; the second row is the suit's absorb share
			float integPct = Math.max(0f, Math.min(100f, menu.suitIntegrityPercentExact()));
			float maxI = suitId == null ? IronManEnergy.MAX_INTEGRITY : IronManEnergy.maxIntegrity(suitId);
			meter(g, 57, Component.translatable("screen.projecthero.suit_call.integrity").getString(), integPct / 100f,
					IronManUiLayout.exact(integPct / 100f * maxI, maxI), integPct < 30f ? IronManGui.RED : IronManGui.GREEN);
			if (suit != null && suit.hasReactor()) {
				// v0.16.7 (user) Era I / Era II: the reactor is back -- the second row is its charge
				// read off the menu's slot stacks (synced every change), not the block entity's (re-sent only on contents)
				float cap = Math.max(1f, suit.energyCapacity());
				ItemStack[] ps = pieces();
				ItemStack ref = ps[1].getItem() instanceof IronManArmorItem ? ps[1] : null;
				for (ItemStack s : ps) {
					if (ref == null && s.getItem() instanceof IronManArmorItem) {
						ref = s;
					}
				}
				float en = ref == null ? 0f : Math.max(0f, Math.min(cap, IronManEnergy.stackEnergy(ref, suitId)));
				meter(g, 78, Component.translatable("screen.projecthero.suit_platform.energy_short").getString(), en / cap,
						IronManUiLayout.exact(en, cap), IronManGui.CYAN);
			} else {
				float absorb = suit == null ? 0f : suit.absorbShare();
				meter(g, 78, Component.translatable("screen.projecthero.suit_call.absorb").getString(), absorb,
						Math.round(absorb * 100f) + "%", IronManGui.BLUE);
			}
		}
		// v0.15.4: the Stark Gantry hint, word-wrapped into the old button strip (y 97..115)
		// v0.16.7: an Era I suit says whether a Gantry is in range (it is only repaired / fast-charged then)
		String hintKey = !eraOne ? "screen.projecthero.suit_platform.gantry_hint"
				: gantry ? "screen.projecthero.suit_platform.gantry_ok" : "screen.projecthero.suit_platform.no_gantry";
		int gy = 97;
		for (var line : font.split(Component.translatable(hintKey), MW)) {
			g.drawString(font, line, MX + 1, gy, eraOne && !gantry ? IronManGui.GOLD : IronManGui.CYAN_DIM, false);
			gy += 9;
			if (gy > 106) {
				break;
			}
		}
		if (!menu.hasStoredSuit()) {
			String hint = Component.translatable("screen.projecthero.suit_platform.empty_hint").getString();
			int ty = 60;
			for (var line : font.split(Component.literal(hint), MW)) {
				g.drawString(font, line, MX + 1, ty, IronManGui.TEXT_MUTED, false);
				ty += 10;
				if (ty > 90) {
					break;
				}
			}
		}
	}

	private IronManSuit platformSuit() {
		String id = storedSuitId();
		return id == null ? null : IronManSuits.byId(id);
	}

	/** "5", or "0.5" for a fractional rate. */
	private static String rate(float perSecond) {
		return perSecond == Math.round(perSecond) ? Integer.toString(Math.round(perSecond))
				: String.format(java.util.Locale.ROOT, "%.1f", perSecond);
	}

	private void meter(GuiGraphics g, int y, String label, float frac, String exact, int fill) {
		g.drawString(font, label, MX, y, IronManGui.TEXT_DIM, false);
		String p = IronManUiLayout.pct(frac);
		g.drawString(font, p, MX + MW - font.width(p), y, IronManGui.TEXT, false);
		IronManGui.slab(g, font, MX + 1, y + 9, MW - 2, frac, fill, exact);
	}

	@Override
	public void render(GuiGraphics g, int mouseX, int mouseY, float partialTick) {
		if (suitcase != null) {
			suitcase.visible = menu.offersSuitcase(); // v0.16.7: only while an Era II suit with a carried form is racked
		}
		super.render(g, mouseX, mouseY, partialTick);
		this.renderTooltip(g, mouseX, mouseY);
		var form = menu.packForm();
		if (suitcase != null && suitcase.visible && suitcase.isHovered() && form != null) {
			IronManSuit s = IronManSuits.byId(form.suitId());
			Component suitName = s == null ? Component.literal(form.suitId()) : Component.translatable(s.nameKey());
			g.renderTooltip(font, font.split(Component.translatable("screen.projecthero.suit_platform.suitcase_tip", suitName,
					new ItemStack(form.packedItem().get()).getHoverName()), 160), mouseX, mouseY);
		}
		if (mouseX >= leftPos + 136 && mouseX < leftPos + 170 && mouseY >= topPos + 29 && mouseY < topPos + 51) {
			// v0.16.7: wrapped (the tip is longer now -- TooltipWrap rule)
			g.renderTooltip(font, font.split(Component.translatable("screen.projecthero.suit_platform.regen_tip",
					rate(IronManSuitPlatformBlockEntity.REGEN_INTEGRITY_PER_SECOND)), 180), mouseX, mouseY);
		}
	}
}
