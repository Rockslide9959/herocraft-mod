package com.projecthero.mod.client.thoracquire;

import com.mojang.blaze3d.vertex.PoseStack;
import com.mojang.blaze3d.vertex.VertexConsumer;
import com.projecthero.mod.ProjectHeroMod;
import com.projecthero.mod.client.thor.ThorDraw;
import com.projecthero.mod.thoracquire.entity.StormwardenBoss;

import net.minecraft.client.renderer.MultiBufferSource;
import net.minecraft.client.renderer.entity.EntityRendererProvider;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.world.phys.Vec3;

import software.bernie.geckolib.model.GeoModel;
import software.bernie.geckolib.renderer.GeoEntityRenderer;
import software.bernie.geckolib.renderer.layer.AutoGlowingGeoLayer;

/**
 * v0.17.7: draws The Stormwarden through GeckoLib ({@code geo/stormwarden.geo.json}, its texture + glowmask and clips, all
 * generated by {@code scratchpad/v0177/gen_stormwarden.js}) plus code-drawn lightning: arcs crawling over the armour (more once
 * Unbound), lightning held on the raised maul during Skyfall, and a crackling column while it forms or surges.
 */
public class StormwardenRenderer extends GeoEntityRenderer<StormwardenBoss> {
	public StormwardenRenderer(EntityRendererProvider.Context context) {
		super(context, new Model());
		this.shadowRadius = 1.1f;
		addRenderLayer(new AutoGlowingGeoLayer<>(this));
	}

	static final class Model extends GeoModel<StormwardenBoss> {
		private static final ResourceLocation MODEL = ProjectHeroMod.id("geo/stormwarden.geo.json");
		private static final ResourceLocation TEXTURE = ProjectHeroMod.id("textures/entity/stormwarden.png");
		private static final ResourceLocation ANIMATION = ProjectHeroMod.id("animations/stormwarden.animation.json");

		@Override
		public ResourceLocation getModelResource(StormwardenBoss animatable) {
			return MODEL;
		}

		@Override
		public ResourceLocation getTextureResource(StormwardenBoss animatable) {
			return TEXTURE;
		}

		@Override
		public ResourceLocation getAnimationResource(StormwardenBoss animatable) {
			return ANIMATION;
		}
	}

	@Override
	protected float getDeathMaxRotation(StormwardenBoss animatable) {
		return 0.0f;
	}

	@Override
	public void render(StormwardenBoss entity, float entityYaw, float partialTick, PoseStack poseStack, MultiBufferSource buffers, int light) {
		super.render(entity, entityYaw, partialTick, poseStack, buffers, light);
		if (entity.isDeadOrDying()) {
			return;
		}
		float time = entity.tickCount + partialTick;
		VertexConsumer vc = ThorDraw.buffer(buffers);
		// ThorDraw wants camera-relative points (its ribbons face the origin): move the origin back to the camera
		Vec3 off = entity.getPosition(partialTick).subtract(entityRenderDispatcher.camera.getPosition());
		poseStack.pushPose();
		poseStack.translate(-off.x, -off.y, -off.z);
		PoseStack.Pose pose = poseStack.last();
		boolean unbound = entity.phase() >= 2;
		// arcs crawling over the plates: short jagged bolts between points on the body, re-shaped a few times a second
		int arcs = unbound ? 4 : 2;
		double seedBase = Math.floor(time / 3.0);
		for (int i = 0; i < arcs; i++) {
			double s = seedBase * 7.1 + i * 13.3 + entity.getId();
			double a0 = ThorDraw.hash(s) * Math.PI * 2;
			double a1 = a0 + 0.8 + ThorDraw.hash(s + 1) * 1.6;
			double y0 = 1.0 + ThorDraw.hash(s + 2) * 2.2;
			double y1 = y0 + (ThorDraw.hash(s + 3) - 0.5) * 1.2;
			Vec3 p0 = new Vec3(Math.cos(a0) * 0.7, y0, Math.sin(a0) * 0.7);
			Vec3 p1 = new Vec3(Math.cos(a1) * 0.7, y1, Math.sin(a1) * 0.7);
			ThorDraw.bolt(vc, pose, ThorDraw.jagged(p0.add(off), p1.add(off), 6, 0.18, s), unbound ? 0.7f : 0.5f, 0.9f);
		}
		byte move = entity.move();
		if (move == StormwardenBoss.MOVE_SKYFALL || move == StormwardenBoss.MOVE_SURGE || move == StormwardenBoss.MOVE_FORM) {
			// lightning pouring down from the sky into it
			double s = Math.floor(time / 2.0) * 3.7 + entity.getId();
			Vec3 top = new Vec3(0, 4.3, 0);
			Vec3 sky = new Vec3((ThorDraw.hash(s) - 0.5) * 2.0, 22, (ThorDraw.hash(s + 1) - 0.5) * 2.0);
			float w = move == StormwardenBoss.MOVE_SKYFALL ? 0.9f : 1.8f;
			ThorDraw.bolt(vc, pose, ThorDraw.jagged(sky.add(off), top.add(off), 14, 1.0, s), w, 0.95f);
		}
		poseStack.popPose();
	}
}
