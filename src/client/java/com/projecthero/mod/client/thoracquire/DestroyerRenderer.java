package com.projecthero.mod.client.thoracquire;

import com.mojang.blaze3d.vertex.PoseStack;
import com.mojang.blaze3d.vertex.VertexConsumer;
import com.projecthero.mod.ProjectHeroMod;
import com.projecthero.mod.client.beamclash.BeamClashClient;
import com.projecthero.mod.client.maxsteel.TurboDraw;
import com.projecthero.mod.client.thor.ThorDraw;
import com.projecthero.mod.thoracquire.entity.DestroyerBoss;

import net.minecraft.client.renderer.MultiBufferSource;
import net.minecraft.client.renderer.RenderType;
import net.minecraft.client.renderer.entity.EntityRendererProvider;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.util.Mth;
import net.minecraft.world.phys.Vec3;

import software.bernie.geckolib.cache.object.BakedGeoModel;
import software.bernie.geckolib.model.GeoModel;
import software.bernie.geckolib.renderer.GeoEntityRenderer;
import software.bernie.geckolib.renderer.GeoRenderer;
import software.bernie.geckolib.renderer.layer.AutoGlowingGeoLayer;

/**
 * v0.17.7: draws The Destroyer through GeckoLib ({@code geo/destroyer.geo.json}, its textures + glowmasks and clips, all
 * generated by {@code scratchpad/v0177/gen_destroyer.js}) plus the code-drawn fire: the molten beam out of its face (the
 * Disintegration Beam, thinner for a Fire Blast), the glow building at its face while the plates open, and the storm's bolt
 * pouring into it while it lands or surges. Unleashed (phase 2) swaps to the texture whose seams blaze; dying, the glow fades
 * out over the collapse. Per the beam rule, the beam hides while a clash draws it ({@link BeamClashClient#hides}).
 *
 * <p>The body is a player-shaped model built from a borrowed skin (user's pick): "Destroyer" on PlanetMinecraft,
 * https://www.planetminecraft.com/skin/destroyer-6483954/ (original kept as scratchpad/v0177/destroyer_skin_original.png). It is
 * 32 units tall at one unit per skin texel, drawn {@link #SCALE}x to stand about 3.6 blocks.
 */
public class DestroyerRenderer extends GeoEntityRenderer<DestroyerBoss> {
	public static final float SCALE = 1.8f;

	public DestroyerRenderer(EntityRendererProvider.Context context) {
		super(context, new Model());
		withScale(SCALE);
		this.shadowRadius = 1.0f;
		addRenderLayer(new FadingGlow(this));
	}

	static final class Model extends GeoModel<DestroyerBoss> {
		private static final ResourceLocation MODEL = ProjectHeroMod.id("geo/destroyer.geo.json");
		private static final ResourceLocation TEXTURE = ProjectHeroMod.id("textures/entity/destroyer.png");
		private static final ResourceLocation TEXTURE_UNLEASHED = ProjectHeroMod.id("textures/entity/destroyer_unleashed.png");
		private static final ResourceLocation ANIMATION = ProjectHeroMod.id("animations/destroyer.animation.json");

		@Override
		public ResourceLocation getModelResource(DestroyerBoss animatable) {
			return MODEL;
		}

		@Override
		public ResourceLocation getTextureResource(DestroyerBoss animatable) {
			return animatable.phase() >= 2 ? TEXTURE_UNLEASHED : TEXTURE;
		}

		@Override
		public ResourceLocation getAnimationResource(DestroyerBoss animatable) {
			return ANIMATION;
		}
	}

	/** The glowmask layer, faded by alpha as the fire goes out over the death (and flickering a little once Unleashed). */
	static final class FadingGlow extends AutoGlowingGeoLayer<DestroyerBoss> {
		FadingGlow(GeoRenderer<DestroyerBoss> renderer) {
			super(renderer);
		}

		@Override
		public void render(PoseStack poseStack, DestroyerBoss animatable, BakedGeoModel bakedModel, RenderType renderType,
				MultiBufferSource bufferSource, VertexConsumer buffer, float partialTick, int packedLight, int packedOverlay) {
			float a = 1f;
			if (animatable.isDeadOrDying()) {
				a = 1f - Mth.clamp((animatable.deathTime + partialTick - 4f) / 30f, 0f, 1f);
			} else if (animatable.phase() >= 2) {
				a = 0.85f + 0.15f * Mth.sin((animatable.tickCount + partialTick) * 0.6f);
			}
			if (a <= 0.01f) {
				return;
			}
			RenderType type = getRenderType(animatable, bufferSource);
			if (type == null) {
				return;
			}
			int colour = (Math.round(a * 255f) << 24) | 0xFFFFFF;
			getRenderer().reRender(bakedModel, poseStack, bufferSource, animatable, type, bufferSource.getBuffer(type), partialTick,
					0xF000F0, packedOverlay, colour);
		}
	}

	@Override
	protected float getDeathMaxRotation(DestroyerBoss animatable) {
		return 0.0f;
	}

	/** No red death tint: the collapse is the hollow armour going dark, not a mob flashing red for 2.5 s. Hits still flash. */
	@Override
	public int getPackedOverlay(DestroyerBoss animatable, float u, float partialTick) {
		if (animatable.isDeadOrDying()) {
			return net.minecraft.client.renderer.texture.OverlayTexture.NO_OVERLAY;
		}
		return super.getPackedOverlay(animatable, u, partialTick);
	}

	@Override
	public void render(DestroyerBoss entity, float entityYaw, float partialTick, PoseStack poseStack, MultiBufferSource buffers, int light) {
		super.render(entity, entityYaw, partialTick, poseStack, buffers, light);
		if (entity.isDeadOrDying()) {
			return;
		}
		float time = entity.tickCount + partialTick;
		byte move = entity.move();
		VertexConsumer vc = ThorDraw.buffer(buffers);
		// ThorDraw wants camera-relative points (its ribbons face the origin): move the origin back to the camera
		Vec3 pos = entity.getPosition(partialTick);
		Vec3 off = pos.subtract(entityRenderDispatcher.camera.getPosition());
		poseStack.pushPose();
		poseStack.translate(-off.x, -off.y, -off.z);
		PoseStack.Pose pose = poseStack.last();

		if (entity.beamOn() && !BeamClashClient.hides(entity)) {
			float yaw = Mth.rotLerp(partialTick, entity.beamYawO, entity.beamYawC);
			Vec3 dir = Vec3.directionFromRotation(entity.beamPitch(), yaw);
			Vec3 fwd = Vec3.directionFromRotation(0f, yaw);
			Vec3 from = new Vec3(fwd.x * DestroyerBoss.FACE_FORWARD, DestroyerBoss.FACE_Y, fwd.z * DestroyerBoss.FACE_FORWARD);
			Vec3 to = from.add(dir.scale(entity.beamLength()));
			boolean blast = move == DestroyerBoss.MOVE_BLAST;
			float w = blast ? 0.6f : 1f;
			float flick = 0.9f + 0.1f * Mth.sin(time * 2.3f);
			// a slightly wavering molten column: a wide orange halo, a hot amber body and a white-hot core
			Vec3[] path = ThorDraw.jagged(from.add(off), to.add(off), 10, 0.05, Math.floor(time / 2.0) * 3.1 + entity.getId());
			ThorDraw.ribbon(vc, pose, path, 0.62f * w * flick, 0xFF5A0A, 0.28f);
			ThorDraw.ribbon(vc, pose, path, 0.38f * w * flick, 0xFF8A26, 0.6f);
			ThorDraw.ribbon(vc, pose, path, 0.2f * w, 0xFFC870, 0.85f);
			ThorDraw.ribbon(vc, pose, path, 0.08f * w, 0xFFF8E0, 1f);
			poseStack.pushPose();
			poseStack.translate(from.x + off.x, from.y + off.y, from.z + off.z);
			TurboDraw.orb(vc, poseStack, 0.42f * w * flick, 0xFF8A26, time * 12f, 0.9f);
			poseStack.popPose();
			poseStack.pushPose();
			poseStack.translate(to.x + off.x, to.y + off.y, to.z + off.z);
			TurboDraw.orb(vc, poseStack, 0.55f * w * flick, 0xFF6A10, time * -9f, 0.8f);
			poseStack.popPose();
		} else if (move == DestroyerBoss.MOVE_BEAM || move == DestroyerBoss.MOVE_BLAST || move == DestroyerBoss.MOVE_SURGE) {
			// the fire building behind the opening plates
			float k = Mth.clamp((time - entity.clientMoveStart) / (move == DestroyerBoss.MOVE_BEAM ? DestroyerBoss.BEAM_WINDUP : 14f), 0f, 1f);
			if (k > 0.2f) {
				Vec3 fwd = Vec3.directionFromRotation(0f, entity.getViewYRot(partialTick));
				poseStack.pushPose();
				poseStack.translate(fwd.x * DestroyerBoss.FACE_FORWARD + off.x, DestroyerBoss.FACE_Y + off.y, fwd.z * DestroyerBoss.FACE_FORWARD + off.z);
				TurboDraw.orb(vc, poseStack, 0.08f + 0.26f * k, 0xFF8A26, time * 10f, 0.25f + 0.6f * k);
				poseStack.popPose();
			}
		}
		if (move == DestroyerBoss.MOVE_SURGE || (move == DestroyerBoss.MOVE_FORM && time - entity.clientMoveStart < 20)) {
			// the storm pouring into it (it is lightning-proof: it only feeds it)
			double s = Math.floor(time / 2.0) * 3.7 + entity.getId();
			Vec3 top = new Vec3(0, 3.7, 0);
			Vec3 sky = new Vec3((ThorDraw.hash(s) - 0.5) * 2.0, 22, (ThorDraw.hash(s + 1) - 0.5) * 2.0);
			ThorDraw.bolt(vc, pose, ThorDraw.jagged(sky.add(off), top.add(off), 14, 1.0, s), 1.6f, 0.9f);
		}
		poseStack.popPose();
	}
}
