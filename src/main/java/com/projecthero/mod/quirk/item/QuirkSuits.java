package com.projecthero.mod.quirk.item;

import java.util.EnumMap;
import java.util.List;
import java.util.Map;

import org.jetbrains.annotations.Nullable;

import com.projecthero.mod.ProjectHeroMod;
import com.projecthero.mod.quirk.Quirk;

import net.minecraft.core.Holder;
import net.minecraft.core.Registry;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.core.registries.Registries;
import net.minecraft.resources.ResourceKey;
import net.minecraft.sounds.SoundEvents;
import net.minecraft.world.entity.EquipmentSlot;
import net.minecraft.world.entity.LivingEntity;
import net.minecraft.world.item.ArmorItem;
import net.minecraft.world.item.ArmorMaterial;
import net.minecraft.world.item.CreativeModeTab;
import net.minecraft.world.item.Item;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.item.Items;
import net.minecraft.world.item.Rarity;
import net.minecraft.world.item.crafting.Ingredient;

/**
 * v0.16.7 (user: "the suits should be craftable and equippable"): the seven Quirk hero suits -- helmet, chestplate,
 * leggings, boots each ({@code <suit>_suit_<piece>}, 28 items). Anyone can wear them, Quirk or not; holding a Quirk no
 * longer changes the player's look. Each worn piece draws ONLY its own body parts from the suit's costume skin
 * ({@code textures/entity/quirk/<quirk>_wide.png} / {@code _slim.png}) over the wearer ({@code client/quirk/QuirkCostume});
 * the vanilla armour model is never drawn for them.
 *
 * <p>v0.16.7: the Ingenium suit has no helmet ({@link #INGENIUM_TYPES}, the old helmet item is retired) and its three
 * pieces are tougher to make up for it ({@link #INGENIUM_MATERIAL}); wearing all three cools Engine's heat build.
 *
 * <p>Iron-level protection (2 / 6 / 5 / 2, no toughness), durability a little above iron ({@link #DURABILITY_MULTIPLIER}
 * vs iron's 15), repaired with iron ingots. Crafted in the vanilla armour shapes from iron + the suit's two themed
 * items ({@code data/projecthero/recipe/<suit>_suit_*.json}, generated by {@code scratchpad/quirk_suits/gen_quirk_suits.js}).
 */
public final class QuirkSuits {
	public static final int DURABILITY_MULTIPLIER = 17;

	/** A suit: its id part, the Quirk whose costume skin it is, and the two themed recipe items (A main, B accent). */
	public enum Suit {
		ENDEAVOR("endeavor", Quirk.HELLFLAME, Items.BLAZE_POWDER, Items.MAGMA_CREAM),
		OVERHAUL("overhaul", Quirk.OVERHAUL, Items.GREEN_WOOL, Items.BONE),
		INGENIUM("ingenium", Quirk.ENGINE, Items.QUARTZ, Items.BLUE_DYE),
		TSUKUYOMI("tsukuyomi", Quirk.DARK_SHADOW, Items.BLACK_WOOL, Items.PHANTOM_MEMBRANE),
		ERASER_HEAD("eraser_head", Quirk.ERASURE, Items.BLACK_WOOL, Items.STRING),
		GROUND_ZERO("ground_zero", Quirk.EXPLOSION, Items.GUNPOWDER, Items.ORANGE_DYE),
		URAVITY("uravity", Quirk.ZERO_GRAVITY, Items.PINK_WOOL, Items.WHITE_WOOL);

		public final String id;
		public final Quirk quirk;
		public final Item main;
		public final Item accent;

		Suit(String id, Quirk quirk, Item main, Item accent) {
			this.id = id;
			this.quirk = quirk;
			this.main = main;
			this.accent = accent;
		}

		public static Suit of(Quirk q) {
			for (Suit s : values()) {
				if (s.quirk == q) {
					return s;
				}
			}
			throw new IllegalArgumentException(String.valueOf(q));
		}

		/** The pieces that make up this suit (v0.16.7: Ingenium has no helmet). */
		public ArmorItem.Type[] pieces() {
			return this == INGENIUM ? INGENIUM_TYPES : TYPES;
		}

		public boolean has(ArmorItem.Type t) {
			for (ArmorItem.Type p : pieces()) {
				if (p == t) {
					return true;
				}
			}
			return false;
		}
	}

	public static final ArmorItem.Type[] TYPES = { ArmorItem.Type.HELMET, ArmorItem.Type.CHESTPLATE, ArmorItem.Type.LEGGINGS,
			ArmorItem.Type.BOOTS };
	/**
	 * v0.16.7 (user: the Ingenium helmet "doesnt work well"): the Ingenium suit is chestplate, leggings and boots. The old
	 * {@code ingenium_suit_helmet} still exists so saves keep it, but it is retired ({@link QuirkSuitItem#retired}): no
	 * recipe (it salvages back into iron), not in the creative tab, no protection, never drawn and no part of the set.
	 */
	public static final ArmorItem.Type[] INGENIUM_TYPES = { ArmorItem.Type.CHESTPLATE, ArmorItem.Type.LEGGINGS, ArmorItem.Type.BOOTS };

	public static Holder<ArmorMaterial> MATERIAL;
	/** v0.16.7: the helmetless Ingenium suit -- 7 / 6 / 2 (the old four-piece total of 15) and 1 toughness a piece. */
	public static Holder<ArmorMaterial> INGENIUM_MATERIAL;
	/** v0.16.7: the retired Ingenium helmet's -- no protection at all. */
	public static Holder<ArmorMaterial> RETIRED_MATERIAL;
	private static final Map<Quirk, Map<ArmorItem.Type, QuirkSuitItem>> PIECES = new EnumMap<>(Quirk.class);

	private QuirkSuits() {
	}

	private static Holder<ArmorMaterial> material(String id, int boots, int legs, int chest, int helmet, float toughness) {
		ArmorMaterial material = new ArmorMaterial(
				Map.of(ArmorItem.Type.BOOTS, boots, ArmorItem.Type.LEGGINGS, legs, ArmorItem.Type.CHESTPLATE, chest, ArmorItem.Type.HELMET, helmet,
						ArmorItem.Type.BODY, 5),
				12, SoundEvents.ARMOR_EQUIP_LEATHER, () -> Ingredient.of(Items.IRON_INGOT),
				// never drawn (the costume layer draws the suit; QuirkSuitArmourMixin skips the vanilla model)
				List.of(new ArmorMaterial.Layer(ProjectHeroMod.id("quirk_suit"))), toughness, 0f);
		return Registry.registerForHolder(BuiltInRegistries.ARMOR_MATERIAL, ResourceKey.create(Registries.ARMOR_MATERIAL, ProjectHeroMod.id(id)),
				material);
	}

	public static void initialize() {
		MATERIAL = material("quirk_suit", 2, 5, 6, 2, 0f);
		INGENIUM_MATERIAL = material("quirk_suit_ingenium", 2, 6, 7, 0, 1f);
		RETIRED_MATERIAL = material("quirk_suit_retired", 0, 0, 0, 0, 0f);
		for (Suit s : Suit.values()) {
			Map<ArmorItem.Type, QuirkSuitItem> m = new EnumMap<>(ArmorItem.Type.class);
			for (ArmorItem.Type t : TYPES) {
				boolean retired = !s.has(t);
				Holder<ArmorMaterial> mat = retired ? RETIRED_MATERIAL : s == Suit.INGENIUM ? INGENIUM_MATERIAL : MATERIAL;
				QuirkSuitItem item = new QuirkSuitItem(s, mat, t,
						new Item.Properties().rarity(retired ? Rarity.COMMON : Rarity.UNCOMMON).durability(t.getDurability(DURABILITY_MULTIPLIER)),
						retired);
				m.put(t, Registry.register(BuiltInRegistries.ITEM, ProjectHeroMod.id(itemId(s, t)), item));
			}
			PIECES.put(s.quirk, m);
		}
	}

	/** {@code endeavor_suit_helmet}... */
	public static String itemId(Suit s, ArmorItem.Type t) {
		return s.id + "_suit_" + t.getName();
	}

	public static QuirkSuitItem piece(Quirk q, ArmorItem.Type t) {
		return PIECES.get(q).get(t);
	}

	/** The Quirk suit worn in this slot (null: none / something else / a retired piece). Client-safe. */
	public static @Nullable Quirk wornIn(LivingEntity entity, EquipmentSlot slot) {
		ItemStack stack = entity.getItemBySlot(slot);
		return stack.getItem() instanceof QuirkSuitItem item && !item.retired ? item.suit.quirk : null;
	}

	/** Every piece of {@code suit} is worn (v0.16.7: the Ingenium set bonus). Client-safe. */
	public static boolean fullSetWorn(LivingEntity entity, Suit suit) {
		for (ArmorItem.Type t : suit.pieces()) {
			if (wornIn(entity, t.getSlot()) != suit.quirk) {
				return false;
			}
		}
		return true;
	}

	public static boolean anyWorn(LivingEntity entity) {
		return wornIn(entity, EquipmentSlot.HEAD) != null || wornIn(entity, EquipmentSlot.CHEST) != null
				|| wornIn(entity, EquipmentSlot.LEGS) != null || wornIn(entity, EquipmentSlot.FEET) != null;
	}

	public static void addToCreativeTab(CreativeModeTab.Output output) {
		for (Suit s : Suit.values()) {
			for (ArmorItem.Type t : s.pieces()) {
				output.accept(PIECES.get(s.quirk).get(t));
			}
		}
	}
}
